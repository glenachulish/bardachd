def decode(b64):
    return base64.b64decode("".join(b64.split()))

def sha12(data):
    return hashlib.sha256(data).hexdigest()[:12]

def main():
    for f in ("main.py", "frontend.py"):
        if not os.path.exists(f):
            print(f"ERROR: {f} not found. Run this from the repo root (where main.py and frontend.py are).")
            sys.exit(1)

    main_new = decode(MAIN_B64)
    fe_new   = decode(FE_B64)
    assert sha12(main_new) == MARKER_MAIN_SHA, "internal: main payload corrupted"
    assert sha12(fe_new)   == MARKER_FE_SHA,   "internal: frontend payload corrupted"

    cur_main = open("main.py","rb").read()
    cur_fe   = open("frontend.py","rb").read()

    already = (sha12(cur_main)==MARKER_MAIN_SHA and sha12(cur_fe)==MARKER_FE_SHA)
    if already:
        print("Already patched (both files match the new version). Nothing to do.")
        return

    stamp = time.strftime("%Y%m%d-%H%M%S")
    bdir = os.path.join(".backups", f"patch-{stamp}")
    os.makedirs(bdir, exist_ok=True)
    open(os.path.join(bdir,"main.py"),"wb").write(cur_main)
    open(os.path.join(bdir,"frontend.py"),"wb").write(cur_fe)
    print(f"Backed up current main.py and frontend.py to {bdir}/")

    open("main.py","wb").write(main_new)
    open("frontend.py","wb").write(fe_new)
    print("Wrote new main.py and frontend.py.")
    print("Verify: python3 -c 'import ast; ast.parse(open(\"main.py\").read()); ast.parse(open(\"frontend.py\").read()); print(\"parse OK\")'")
    print("Then restart the service on the Pi:  sudo systemctl restart bardachd")

if __name__ == "__main__":
    main()
